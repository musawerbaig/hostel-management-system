const photos = (n: number): string[] => [
  `https://picsum.photos/seed/isb${n}a/800/600`,
  `https://picsum.photos/seed/isb${n}b/800/600`,
  `https://picsum.photos/seed/isb${n}c/800/600`,
];

const COMSATS_PRESET = ['COMSATS University Islamabad'];

function listing(
  base: Omit<SeedInput, 'verificationDocs' | 'nearbyUniversities' | 'rejectionReason' | 'verifiedAt' | 'verifiedBy'>,
): SeedInput {
  return {
    ...base,
    verificationDocs: [],
    nearbyUniversities: COMSATS_PRESET,
    rejectionReason: '',
    verifiedAt: '',
    verifiedBy: '',
  };
}

